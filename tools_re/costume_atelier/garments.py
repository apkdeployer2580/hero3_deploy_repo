def coat_keys(coat, lining, hem, coat_z=4, back_z=1):
    """The palette entries for LONG_COAT from three ramps (6 hex colours each)."""
    from engine import Mat
    p = {}
    for t in range(6):
        p[str(t)] = Mat(coat, z=coat_z, flat=t, fam='coat')
    for i, t in enumerate(range(5)):
        p['abcde'[i]] = Mat(coat, z=back_z, flat=t, fam='coatb')
    p['L'] = Mat(lining, z=coat_z, flat=1, fam='coat')
    p['M'] = Mat(lining, z=coat_z, flat=3, fam='coat')
    p['l'] = Mat(lining, z=back_z, flat=1, fam='coatb')
    p['G'] = Mat(hem, z=coat_z, flat=4, fam='coat')
    p['H'] = Mat(hem, z=coat_z, flat=2, fam='coat')
    p['g'] = Mat(hem, z=back_z, flat=3, fam='coatb')
    p['h'] = Mat(hem, z=back_z, flat=1, fam='coatb')
    return p


