def post_legs(g, i):
    kit.cuff(g, 'B', {'P'}, 'Q')
    zones = bodies.legs()[i][0]
    for y in range(1, g.h):
        for x in range(g.w):
            if zones[y][x] in 'Aa' and zones[y - 1][x] in 'Ss' and g.keys[y][x] == 'B':
                g.keys[y][x] = 'Z'


def post_arms(g, i):
    # the sleeve is rolled up: the last sleeve pixels before the wrist wrap take a lighter fold
    for y in range(g.h):
        for x in range(g.w):
            if g.keys[y][x] == 'R' and any(g.get(x + dx, y + dy) == 'C' for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                g.keys[y][x] = 'O'


