def short_coat(i):
    rows = garments.LONG_COAT[i].strip('\n').split('\n')
    cut = HEM[i]
    out = []
    for y, r in enumerate(rows):
        if y < cut:
            out.append(r)
        elif y == cut:
            s = ''
            for c in r:
                if c in '012345':
                    s += 'G' if c in LIT else 'H'
                elif c in 'GH':
                    s += c
                elif c in 'abcde':
                    s += 'g' if c in 'cde' else 'h'
                elif c == 'L':
                    s += 'L'
                elif c == 'M':
                    s += 'M'
                else:
                    s += c
            out.append(s)
        else:
            out.append(''.join('~' if c != '.' else '.' for c in r))
    return '\n'.join(out)


