def _flake():
    out = [('ring', 0.97, 2), ('ring', 0.88, 1)]
    for k in range(6):
        a = math.radians(90 + 60 * k)
        out.append(('seg', 0, 0, 0.82 * math.cos(a), 0.82 * math.sin(a), 2))
        for r0, r1, spread in ((0.46, 0.66, 30),):
            for sgn in (-1, 1):
                b = a + math.radians(sgn * spread)
                out.append(('seg', r0 * math.cos(a), r0 * math.sin(a), r1 * math.cos(b), r1 * math.sin(b), 1))
    out.append(('dots', 6, 0.82, 90, 2))
    out.append(('dots', 1, 0, 0, 3))
    return out


