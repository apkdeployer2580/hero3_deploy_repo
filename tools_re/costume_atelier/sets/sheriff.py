def stamp(size, x, y, block):
    """A sparse overlay: `block` placed at (x, y) in an otherwise empty frame of `size`."""
    w, h = size
    rows = [l for l in block.split('\n') if l.strip()]
    grid = [['.'] * w for _ in range(h)]
    for j, r in enumerate(rows):
        for i, c in enumerate(r):
            if c != '.' and 0 <= x + i < w and 0 <= y + j < h:
                grid[y + j][x + i] = c
    return '\n'.join(''.join(r) for r in grid)


