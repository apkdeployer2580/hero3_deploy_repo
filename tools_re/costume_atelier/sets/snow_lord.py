def _merge(hair, horns):
    hr = [r for r in hair.strip('\n').split('\n')]
    nr = [r for r in horns.strip('\n').split('\n')]
    w = max(len(r) for r in hr + nr)
    out = []
    for y in range(max(len(hr), len(nr))):
        a = (hr[y] if y < len(hr) else '').ljust(w, '.')
        b = (nr[y] if y < len(nr) else '').ljust(w, '.')
        out.append(''.join(q if q != '.' else p for p, q in zip(a, b)))
    return '\n'.join(out)


