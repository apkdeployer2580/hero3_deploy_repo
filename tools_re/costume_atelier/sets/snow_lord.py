def _lerp(a, b, t):
    return round(a + (b - a) * t)


def _h(x, i):
    return (x * 7 + i * 3) % 5


def _gap(x, i):
    return _h(x, i) == 0


def _long(x, i):
    return _h(x, i) == 3


def post_legs(g, i):
    # 1) the boots' shaggy fur tops: a ragged rim over the trousers/knees
    tops = [(x, y) for y in range(1, g.h) for x in range(g.w)
            if g.keys[y][x] == 'B' and g.keys[y - 1][x] in ('P', 'K')]
    for x, y in tops:
        g.keys[y][x] = 'Y' if x % 2 else 'X'
        g.pins[y][x] = None
        if x % 3 == 1:
            g.keys[y - 1][x] = 'V'
            g.pins[y - 1][x] = None
    # tassets: horizontal lames (a dark seam every third row)
    for y in range(g.h):
        for x in range(g.w):
            if g.keys[y][x] == 'Z' and y % 3 == 0 and y > 1:
                g.pins[y][x] = 1
    # 2) the cloak
    mode, top, hem, l0, r0, l1, r1, p0, p1 = CLOAK[i]
    legs = [[g.keys[y][x] is not None for x in range(g.w)] for y in range(g.h)]
    cell = {}
    for y in range(top, min(hem, g.h - 1) + 1):
        t = (y - top) / max(1, hem - top)
        a, b = _lerp(l0, l1, t), _lerp(r0, r1, t)
        a, b = max(0, a), min(g.w - 1, b)
        if mode == 'back':           # the cloak's back always covers the full width of the legs
            xs = [x for x in range(g.w) if legs[y][x]]
            if xs:
                a, b = min(a, xs[0]), max(b, xs[-1])
        tuft = y == hem
        if mode == 'front':
            pw = _lerp(p0, p1, t)
            for x in range(a, b + 1):
                inl = x < a + pw
                inr = x > b - pw
                if tuft and _gap(x, i):
                    continue
                if inl or inr:
                    lw = 2 if pw >= 4 else 1
                    lin = (a + pw - lw <= x <= a + pw - 1) or (b - pw + 1 <= x <= b - pw + lw)
                    kind = 'fur' if y >= hem - 1 else ('lining' if lin else 'cloth')
                    cell[(x, y)] = (kind, True, a, b, 'L' if inl else 'R')
                elif not legs[y][x] and y >= top + 2:
                    cell[(x, y)] = ('fur' if y >= hem - 1 else 'lining', False, a, b, 'M')
        else:
            for x in range(a, b + 1):
                if tuft and _gap(x, i):
                    continue
                kind = 'fur' if y >= hem - 1 else 'cloth'
                if mode == 'side' and x == a and kind == 'cloth':
                    kind = 'lining'
                cell[(x, y)] = (kind, True, a, b, 'B')
    if hem + 1 < g.h:          # the longest tufts hang one row lower
        for (x, y), v in list(cell.items()):
            if y == hem and v[0] == 'fur' and _long(x, i) and (x, hem + 1) not in cell:
                if v[1] or not legs[hem + 1][x]:
                    cell[(x, hem + 1)] = v
    for (x, y), (kind, over, a, b, part) in cell.items():
        w = max(1, b - a)
        rel = (x - a) / w
        edge = None
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            n = (x + dx, y + dy)
            if n in cell:
                continue
            nx, ny = n
            inside = 0 <= nx < g.w and 0 <= ny < g.h
            if not inside or not legs[ny][nx]:
                edge = 0
                break
            if over:
                edge = 1
        if kind == 'lining':
            t = 2 if (x + y) % 4 == 0 else 1
            if part == 'M':
                t = 1 if (x % 3) else 2
            if edge == 0:
                t = 0
            key = ('JLMN' if over else 'jlmn')[t]
        else:
            if kind == 'fur':
                h = _h(x, i)
                t = 5 if h in (1, 2) else 4
                if y == hem:
                    t = 4 if h in (1, 4) else 3
                if y > hem:
                    t = 3
                if part == 'R' or rel > 0.7:
                    t -= 1
                if edge == 0:
                    t = min(t, 3) if y == hem else min(t, 2)
                elif edge == 1:
                    t = min(t, 3)
            else:
                t = 3
                if mode in ('back', 'side'):
                    t = 4 if rel < 0.28 else (3 if rel < 0.62 else 2)
                    for f in (0.34, 0.68):
                        fx = a + f * w
                        if abs(x - fx) < 0.5:
                            t += 1
                        elif 0.5 <= x - fx < 1.5:
                            t -= 1
                    t = max(2, min(4, t))
                    if y == hem - 2:
                        t = min(t, 2)
                elif part == 'L':
                    t = 4 if x == a else 3
                elif part == 'R':
                    t = 2 if x == b else 3
                if rel < 0.06:
                    t = max(t, 4)
                if rel > 0.94:
                    t = min(t, 2)
                if y <= top + 1:
                    t = min(t, 2)
                if edge == 0:
                    t = 0
                elif edge == 1:
                    t = min(t, 1)
            key = (CLOAK_OVER if over else CLOAK_UNDER)[max(0, min(5, t))]
        g.keys[y][x] = key
        g.tones[y][x] = None
        g.pins[y][x] = None


