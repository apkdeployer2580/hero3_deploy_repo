#!/usr/bin/env python3
"""Emit the served cash-shop catalog as a Rust table for the OFFLINE engine.

Why a generator instead of a hand-written table
-----------------------------------------------
The catalog is over a hundred rows of 20 opaque bytes, and it is not a constant: it is built
by `hero3_protocol` out of five tier tables, two content flags and a delist set,
each of which carries a paragraph of reasoning about a device measurement
(`CASH_SHOP.md` is the canonical account). Hand-copying it into Rust would create
a second source of truth that silently rots the first time a row is added, and the
symptom would be a player buying an item the server has delisted — or, worse, an
item id the client resolves to something else.

So the offline engine's table is GENERATED from the same python objects the online
server serves, and the generated file records exactly which objects and with which
flags. Re-run after any catalog change:

    python tools_re/gen_cash_catalog.py            # writes wie_android/src/cash_catalog.rs
    python tools_re/gen_cash_catalog.py --check     # CI-style: fail if stale

`--check` is what keeps the two honest: it regenerates in memory and compares, so a
catalog edit that forgets the Rust side fails loudly instead of shipping a divergent
offline shop.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "hero3_server"))

import hero3_protocol as hp  # noqa: E402  (needs the path above)

OUT = ROOT / "wie_android" / "src" / "cash_catalog.rs"


def served_catalog() -> list[bytes]:
    """Exactly what `ProtocolHandler._cash_catalog_served` returns with the
    shipped defaults, computed from the same tables so the two cannot diverge."""
    h = hp.ProtocolHandler(sid=0, store=None, logfn=lambda _m: None)
    return [bytes(r) for r in h._cash_catalog_served()]


def render(rows: list[bytes]) -> str:
    flags = {
        "cash_paginate": hp.ProtocolHandler.__dataclass_fields__["cash_paginate"].default,
        "cash_sell_top_tier": hp.ProtocolHandler.__dataclass_fields__["cash_sell_top_tier"].default,
        "cash_sell_final_tier": hp.ProtocolHandler.__dataclass_fields__["cash_sell_final_tier"].default,
        "cash_sell_final_variants": hp.ProtocolHandler.__dataclass_fields__["cash_sell_final_variants"].default,
    }
    body = []
    for r in rows:
        cat, idx = r[8], r[9]
        cells = ", ".join(f"0x{b:02x}" for b in r)
        body.append(f"    [{cells}], // cat 0x{cat:02x} idx 0x{idx:02x}")
    # Plain `//`, never `//!`: this file is `include!`d by `offline_selftest.rs` and
    # an inner doc comment cannot appear inside an include (the same rule CLAUDE.md
    # states for `guest_anchors.rs`).
    flag_lines = "\n".join(f"//    {k} = {v}" for k, v in flags.items())
    return f"""// @generated by tools_re/gen_cash_catalog.py — DO NOT EDIT BY HAND.
//
// The cash-shop rows the OFFLINE engine serves, byte-identical to what
// `hero3_server/hero3_protocol.py` sends online. Regenerate after any catalog
// change and re-run the `--check` mode; a divergence here means the offline shop
// sells something the online one does not (or an id the client resolves to a
// different item).
//
// Source objects: `ProtocolHandler._cash_catalog_served()` over
// `CASH_SHOP_ALL` = CASH_SHOP_CAT12 + CASH_SHOP_BULK + CASH_SHOP_MATERIAL
//                 + CASH_SHOP_CAT13 + CASH_SHOP_EQUIP + CASH_SHOP_TOP_TIER
//                 + CASH_SHOP_FINAL_TIER,
// with the shipped flags:
{flag_lines}
//
// Row layout (20 B, established by the 오브 결합 work and matched against live rows
// the device sent): [0..8] instance key, [8] category, [9] index, [10..12] qty u16,
// [12..16] slot marker 0xffffffff, [16] total sockets, [17] refine, [18] filled,
// [19] socketed orb id. The client resolves NAME, EFFECT and PRICE from (cat, idx)
// out of the game's own `dat/i*_dat`, so nothing here needs a name.
//
// The canonical account of WHAT each row is and WHY it is (not) listed lives in
// `hero3_server/CASH_SHOP.md`.

/// One catalog row as it goes on the wire.
pub const ROW_LEN: usize = 20;

/// The served catalog, in page order.
pub const CATALOG: [[u8; ROW_LEN]; {len(rows)}] = [
{chr(10).join(body)}
];
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the generated file is stale")
    args = ap.parse_args()

    rows = served_catalog()
    if len(rows) != len(set(rows)):
        print(f"WARN: catalog has duplicate rows ({len(rows)} rows, {len(set(rows))} distinct)")
    text = render(rows)

    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"STALE: {OUT} does not match the python catalog ({len(rows)} rows).")
            print("Run: python tools_re/gen_cash_catalog.py")
            return 1
        print(f"OK: {OUT.name} matches the python catalog ({len(rows)} rows)")
        return 0

    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(rows)} rows)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
