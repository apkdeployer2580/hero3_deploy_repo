"""Generate `wie_android/src/guardian_rewards.rs` — the 하늘성 EXIT-reward pools.

The player's design (137차 2026-09-25, decisions 2026-09-29 — `TOWER_REWARD_BALANCE_DRAFT.md`
§3): a run pays ONCE when it ends, for the highest boss it cleared. The tiers themselves
(how many shards, which bands, the 1 / 3 / 10 % endgame chance) are `guardian::REWARD_TIERS`
— rules, in the pure file. This module turns the shipped item database into the POOLS
those rules draw from; it is data only, the same contract `cash_catalog.rs` has.

★ 138차 replaced the 85차 pools: `ORDINARY` (등급 <= 3 gear for floors 1..20) and
`JACKPOT` (the 0.1 % 등급 4 roll) belonged to the floor-by-floor payout, which is gone.

THE POOLS

* MATERIAL = the tower-only `{닉스코어파편` (151차 name) appended by `add_tower_material.py`, paid
  N at a time straight into the 재료가방 (`BagBoxHost::grant_boxed`). Read back from the
  asset rather than hardcoded, so a drifted row count fails here instead of at runtime.

* LEGACY = the 78 `"` rows (`add_legacy_items.py` / `add_legacy_boots.py`) with their
  등급 (85제 / 90제), IN THE SAME ORDER as `helldrop_table::HELL_ITEMS` — they come out of
  the one function that table is generated from (`gen_helldrop_table.legacy_rows`), so the
  two can never disagree. The real-item tiers (60..100) cut bands out of it and the endgame
  chance takes the rows at 등급 >= 90 (142차: the 90제, 43; was 요구레벨 >= 95 = 31).

* RECIPES = every `i15_dat` record (조합서, cat 0x0f) whose tail PRODUCES a LEGACY row,
  carrying the RESULT's 등급 — the tiers pick a recipe by what it makes. They are the
  138차 rows `add_tower_recipes.py` writes; on an asset without them this pool is EMPTY
  and the exit reward pays the shards (and the real item) with no recipe — fail closed,
  never an index into rows the game does not have.

★ 150차 (2026-10-01): the number is the TIER (`gen_legacy_items.legacy_tiers`), not the
asset's 요구레벨 byte — the reworked accessories carry 요구 Lv 1 and stay 85/90제 pieces, and
without the split nine of them would silently fall out of the (85,85) / (90,90) bands and the
endgame set (`guardian_selftest` feeds synthetic pools and could not notice). Every value is
asserted to be 85 or 90. ⛔ The Rust field keeps its 138차 name `req_lv` (guardian.rs /
emulator.rs read it) — it holds the tier; for every row that shipped before 150차 that is the
same number, so `guardian_rewards.rs` did not change.

Usage:
    python tools_re/gen_guardian_rewards.py [--zip <asset>] [--out <rs>] [--check]
"""
import argparse
import io
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dump_item_db as DB  # noqa: E402
import gen_helldrop_table as HD  # noqa: E402
import h3crypt  # noqa: E402

DEFAULT_ZIP = os.path.join("android_app", "app", "src", "main", "assets", "hero3_fixed.zip")
DEFAULT_OUT = os.path.join("wie_android", "src", "guardian_rewards.rs")

MATERIAL_CAT = HD.MATERIAL_CAT
MATERIAL_NAME = HD.MATERIAL_NAME
RECIPE_CAT = HD.RECIPE_CAT
ENDGAME_MIN_LV = 90      # guardian::ENDGAME_MIN_LV (142차: the 90제) — a TIER since 150차
TIERS = (85, 90)         # 85제 · 90제 — `gen_helldrop_table.TIERS`
LEGACY_ROWS = 78         # the 133차/133차-B count — `gen_helldrop_table --check` pins it too


def material_idx(jar):
    # ★ 152차: one definition, shared with the hell drop's `HELL_SHARD`.
    return HD.material_idx(jar)


def _tiers_only(rows, what):
    bad = [(c, i, t, n) for c, i, t, n in rows if t not in TIERS]
    if bad:
        raise SystemExit(f"{what}: {len(bad)} row(s) outside the tiers {TIERS}: {bad[:4]} — the 85/90제 "
                         "split must come from gen_legacy_items.legacy_tiers, not the 요구레벨 byte")
    return rows


def legacy(jar):
    """`[(cat, idx, tier, name)]` in `HELL_ITEMS` order (the tier is 85 or 90)."""
    rows = [(cat, idx, tier, name) for cat, idx, tier, name, _main in HD.legacy_rows(jar)]
    if len(rows) != LEGACY_ROWS:
        raise SystemExit(f"{len(rows)} legacy rows, expected {LEGACY_ROWS} — is the asset chain applied?")
    return _tiers_only(rows, "LEGACY")


def recipes(jar, legacy_rows):
    """`[(0x0f, idx, result tier, result name)]` for every 조합서 that makes a LEGACY row.
    ★ 152차: the one definition `gen_helldrop_table.HELL_RECIPES` is generated from too, so the
    tower's recipe pool and the hell drop's can never disagree."""
    return _tiers_only(HD.recipe_rows(jar, legacy_rows), "RECIPES")


def render(legacy_rows, recipe_rows, mat):
    def rows(items):
        return "".join(
            f"    RewardItem {{ cat: {c:#04x}, idx: {i:#04x}, req_lv: {lv} }}, // {n}\n"
            for c, i, lv, n in items)

    endgame = sum(1 for _c, _i, lv, _n in legacy_rows if lv >= ENDGAME_MIN_LV)
    return f'''// GENERATED by tools_re/gen_guardian_rewards.py — do not edit by hand.
//
// The 하늘성 EXIT-reward pools (138차), read out of the shipped item database. The rules
// that draw from them are `guardian::{{REWARD_TIERS, exit_payout}}`.
// Regenerate (and verify) with:
//     python tools_re/gen_guardian_rewards.py --check
//
// LEGACY = the {len(legacy_rows)} `"` rows in `helldrop_table::HELL_ITEMS` order, with their 등급 — the
// 85제 / 90제 tier ({endgame} of them at >= {ENDGAME_MIN_LV} — the endgame rows). RECIPES = the {len(recipe_rows)} 조합서 whose
// tail makes a LEGACY row, carrying the RESULT's 등급 (empty on an asset without the 138차
// recipe rows — the exit reward then pays no recipe, fail closed).
//
// ⚠ Indices are WIRE indices `(cat, idx)`, valid only for an asset that carries these rows
// AND a `binary_patches.toml` whose count table says so.

/// One candidate. `req_lv` is the TIER — 85 (85제) or 90 (90제), for a 조합서 the tier of what
/// it makes (`gen_legacy_items.legacy_tiers`). It kept its 138차 name: until 150차 it was the
/// game's own 요구레벨, the same number for every row, but a reworked accessory's 요구레벨 is 1
/// and it is still an 85/90제 piece.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct RewardItem {{
    pub cat: u8,
    pub idx: u8,
    pub req_lv: u8,
}}

/// The tower-only material appended by `tools_re/add_tower_material.py`.
pub const MATERIAL: RewardItem = RewardItem {{ cat: {MATERIAL_CAT:#04x}, idx: {mat:#04x}, req_lv: 0 }};

pub const LEGACY: &[RewardItem] = &[
{rows(legacy_rows)}];

pub const RECIPES: &[RewardItem] = &[
{rows(recipe_rows)}];
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--zip", default=DEFAULT_ZIP)
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true",
                    help="regenerate and compare against --out (exit 1 on drift)")
    a = ap.parse_args()

    jar = h3crypt.open_assets(a.zip)
    mat = material_idx(jar)
    legacy_rows = legacy(jar)
    recipe_rows = recipes(jar, legacy_rows)
    text = render(legacy_rows, recipe_rows, mat)
    what = f"LEGACY {len(legacy_rows)}, RECIPES {len(recipe_rows)}, material idx {mat:#04x}"

    if a.check:
        have = io.open(a.out, encoding="utf-8", newline="").read() if os.path.exists(a.out) else None
        # ★ 135차 §3 ⓑ: compare with LF line endings. A Windows checkout (core.autocrlf)
        # hands the working tree CRLF while this script writes LF, and a gate that is red
        # on every such checkout is noise nobody reads.
        if have is not None:
            have = have.replace("\r\n", "\n")
        if have != text:
            print(f"FAIL: {a.out} is not what this script generates (stale or edited)")
            return 1
        print(f"OK: {a.out} matches - {what}")
        return 0

    io.open(a.out, "w", encoding="utf-8", newline="\n").write(text)
    print(f"wrote {a.out} - {what}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
