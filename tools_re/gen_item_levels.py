"""Regenerate `wie_android/src/item_levels.rs` — every equipment row's grade and 요구레벨.

136차 (2026-09-25): the 정렬 button sorts the bag and the warehouse by 부위 → 요구레벨 ↓ →
등급 ↓ (`bagsort.rs`). The worker could read a live DB row for the bag, but the warehouse
rows are host records (`offline::Store`) with no guest memory behind them, and one table
shared by both sides is one rule — so the numbers come FROM THE SHIPPED ASSET, the same way
`gen_helldrop_table.py` reads the hell pool: a stale table cannot outlive `--check`.

Stat bytes (`dump_item_db.py`): a 20-byte equipment row (i0..i11) carries 등급 at `b7`
and 요구레벨 at `b8`; the 18-byte accessory row (i12) carries them at `b5` / `b6` (`b7` is
the 혼 slot flag there — `LEGACY_ITEMS_70_99.md §5.7`). `add_legacy_items.py` appends rows
to these files, so run this AFTER the asset chain.

★ 150차 (2026-10-01): a `"` legacy row's level column is its TIER (85제 / 90제,
`gen_legacy_items.legacy_tiers`), not its 요구레벨 byte. The reworked accessories carry 요구 Lv 1
(`acc_options.REQ_LV`) while staying 85/90제 pieces; reading the byte would move the nine from
the head of the accessory group (Lv85/90) to the tail among the Lv1 stock rows — the 정렬
order the player had would change for no decision of theirs. For every other `"` row the
tier IS the 요구레벨 byte (cross-checked here), and the boss `{` rows keep their byte (1), so
the table's values did not change.

Usage:
    python tools_re/gen_item_levels.py [--zip <asset.zip>] [--check]
"""
import argparse
import io
import os
import sys
import zipfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import acc_options as AO  # noqa: E402
import dump_item_db as DB  # noqa: E402
import gen_legacy_items as GL  # noqa: E402

DEFAULT_ZIP = os.path.join("android_app", "app", "src", "main", "assets", "hero3_fixed.zip")
OUT = os.path.join("wie_android", "src", "item_levels.rs")
ACC_CAT = 12


def open_jar(zip_path):
    z = zipfile.ZipFile(zip_path)
    jars = [n for n in z.namelist() if n.lower().endswith(".jar")]
    if len(jars) != 1:
        raise SystemExit(f"expected exactly one jar in {zip_path}")
    return zipfile.ZipFile(io.BytesIO(z.read(jars[0])))


def rows(jar):
    dats = {}
    for n in jar.namelist():
        b = os.path.basename(n)
        if b.startswith("i") and b.endswith("_dat") and b[1:-4].isdigit():
            dats[int(b[1:-4])] = jar.read(n)
    tiers = GL.legacy_tiers()
    out = []
    for cat in range(0, 13):
        for idx, _off, body in DB.records(dats[cat]):
            nl = body[0]
            raw, stats = body[1:1 + nl], body[1 + nl:]
            if len(stats) < 9:
                raise SystemExit(f"i{cat}_dat idx {idx:#x}: stats are {len(stats)} B")
            grade, req = (stats[5], stats[6]) if cat == ACC_CAT else (stats[7], stats[8])
            name = raw.lstrip(b"@|${}'\"").decode("euc-kr", "replace")
            if raw[:1] == bytes([GL.NEW_MARK]):
                # ★ 150차: a `"` row sorts by its tier (see the header); the byte must agree.
                tier = tiers.get((cat, name))
                if tier is None:
                    raise SystemExit(f"i{cat}_dat idx {idx:#x}: `\"{name}` is not a legacy row gen_legacy_items knows")
                want_req = AO.REQ_LV if cat == ACC_CAT else tier
                if req != want_req:
                    raise SystemExit(f"i{cat}_dat idx {idx:#x} {name}: 요구레벨 byte {req}, want {want_req} "
                                     "— run the asset chain first")
                req = tier
            out.append((cat, idx, grade, req, name))
    return out


def render(items) -> str:
    lines = [
        "// GENERATED by `python tools_re/gen_item_levels.py` — DO NOT EDIT BY HAND.",
        "//",
        "// Every equipment row of the shipped asset (i0..i12) as `(cat, idx, 등급, 요구레벨)`,",
        "// sorted by `(cat, idx)` — the 정렬 button's level and grade source (`bagsort.rs`, 136차).",
        "// ★ 150차: a `\"` legacy row's level is its 85제 / 90제 tier (a reworked accessory's",
        "// 요구레벨 byte is 1; the order must not move) — `gen_legacy_items.legacy_tiers`.",
        "// Regenerate after any asset change; `--check` gates it. Plain `//` on purpose: the",
        "// file is `include!`d by `bagsort_selftest.rs`, where an inner doc comment cannot go.",
        "",
        f"pub const ITEM_LEVELS: [(u8, u8, u8, u8); {len(items)}] = [",
    ]
    for cat, idx, grade, req, name in items:
        lines.append(f"    (0x{cat:02x}, 0x{idx:02x}, {grade}, {req}), // {name}")
    lines.append("];")
    lines += [
        "",
        "/// `(등급, 요구레벨)` of an equipment row, or `None` for anything the table does not",
        "/// hold (a non-equipment category, or an index past the shipped rows).",
        "pub fn item_level(cat: u16, idx: u16) -> Option<(u8, u8)> {",
        "    let (Ok(c), Ok(i)) = (u8::try_from(cat), u8::try_from(idx)) else {",
        "        return None;",
        "    };",
        "    ITEM_LEVELS",
        "        .binary_search_by(|row| (row.0, row.1).cmp(&(c, i)))",
        "        .ok()",
        "        .map(|at| (ITEM_LEVELS[at].2, ITEM_LEVELS[at].3))",
        "}",
    ]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--zip", default=DEFAULT_ZIP)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    items = rows(open_jar(a.zip))
    if len(items) < 500:
        raise SystemExit(f"{a.zip}: only {len(items)} equipment rows — is this the shipped asset?")
    text = render(items)
    lv = sorted({r[3] for r in items})
    if a.check:
        try:
            have = open(OUT, encoding="utf-8", newline="").read()
        except FileNotFoundError:
            raise SystemExit(f"STALE: {OUT} does not exist — run this tool without --check")
        if have.replace("\r\n", "\n") != text:
            raise SystemExit(f"STALE: {OUT} does not match {a.zip} — rerun this tool")
        print(f"CHECK OK: {OUT} matches the asset ({len(items)} rows, 요구레벨 {lv[0]}..{lv[-1]})")
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {OUT}: {len(items)} rows, 요구레벨 {lv[0]}..{lv[-1]}")


if __name__ == "__main__":
    main()
