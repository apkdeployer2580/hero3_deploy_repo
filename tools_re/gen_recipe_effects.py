"""Generate `vendor/wie/wie_util/src/recipe_effects.rs` — the 하늘성 조합서's 「효과」 second line.

WHY (151차, 2026-10-01). Every game screen that summarises a 조합서 (cat 0x0f) — the bag's
효과 box, the smith's 특수조합 list, the online 싱글가방 — draws two 효과 lines: the recipe
text up to its first `;`, then `sprintf("%s%s", <recipe name>, InGame_txt[79])` =
「템플러헬름의조합설명서」 (seven `"%s%s"` sites: 0x105f2 · 0x11702 · 0x1281e · 0x20ae6 ·
0x23166 · 0x2442e · 0x4221a; the eighth, 0x203cc, is `"%s / %s"` and never sees a 조합서).
The user asked for the material instead: 「닉스코어파편 N개」. That line is not an asset field,
and its name is the bag record's own copy (made when the item was given), so the swap happens
where the line is formatted: `wie_wipi_c`'s `MC_knlSprintk` asks [`manual_line`] and, for a
하늘성 조합서, writes this table's line instead. Shipped 조합서 keep the game's own line.

★ THE ONLINE 싱글가방 passes NO NAME there: its painter (0x1281e) indexes the bag with stale
locals and hands sprintf an empty string, so the shipped game prints 「의조합설명서」 alone for
every recipe (probe: `name=""`). The same painter formats the 이름 line `"%s %s"` (<DB name>,
InGame_txt[115] 「조합서」) as the call just before, so sprintk keeps [`recipe_index`] of THAT
call for exactly one call and falls back to it (`MC_knlSprintk`, `LAST_TOWER_RECIPE`).

WHAT IT READS. `add_tower_recipes.plan()` (pure: the 78 results, their shard counts, the row
order) and `add_tower_recipes.SHARD_NAME`. `--check` additionally proves, on the asset, that
InGame_txt rows 79 / 115 are still those words, that every 하늘성 조합서 row (i15 0x27..0x74)
is named `"<result>` and carries the same 「<shard> N개」 segment in its text — so the table can
never disagree with the recipe the player holds.

Usage:
    python tools_re/gen_recipe_effects.py [--zip <asset.zip>] [--check] [--out <path>]
"""
import argparse
import io
import os
import struct
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import add_tower_recipes as AR     # noqa: E402
import h3crypt                     # noqa: E402

REPO = os.path.abspath(os.path.join(HERE, ".."))
OUT = os.path.join(REPO, "vendor", "wie", "wie_util", "src", "recipe_effects.rs")
DEFAULT_ZIP = os.path.join(REPO, "android_app", "app", "src", "main", "assets", "hero3_fixed.zip")
MANUAL_ROW, MANUAL_SUFFIX = 79, "의조합설명서"     # InGame_txt — the 효과 second line's word
RECIPE_ROW, RECIPE_WORD = 115, "조합서"           # InGame_txt 0x73 — the 이름 line's word
COLOUR_ESCAPES = '@|${}\'"'                       # rodata 0x5b2bc — `gamefont::COLOUR_ESCAPES`


def effect_text(shards):
    return f"{AR.SHARD_NAME} {shards}개"


def rows():
    """[(recipe idx, result name, effect line)] in row order."""
    return [(AR.FIRST + i, r["result"], effect_text(r["shards"])) for i, r in enumerate(AR.plan())]


def rust_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render():
    table = rows()
    names = [n for _i, n, _t in table]
    if len(set(names)) != len(names):
        raise SystemExit("two 하늘성 조합서 share a result name — the table would be ambiguous")
    for _i, n, t in table:
        for s in (n, t):
            s.encode("euc-kr")     # the game font is KS X 1001 + ASCII
    lines = [
        "//! GENERATED by `python tools_re/gen_recipe_effects.py` — DO NOT EDIT BY HAND.",
        "//!",
        "//! 151차 (2026-10-01): the 하늘성 조합서's 「효과」 second line. Every screen that summarises a",
        "//! 조합서 draws `sprintf(\"%s%s\", <recipe name>, InGame_txt[79] \"의조합설명서\")` there",
        "//! (seven sites: 0x105f2 · 0x11702 · 0x1281e · 0x20ae6 · 0x23166 · 0x2442e · 0x4221a);",
        "//! `wie_wipi_c`'s `MC_knlSprintk` asks [`manual_line`] and shows the recipe's material",
        "//! instead. Shipped 조합서 are not in the table and keep the game's own line. The online",
        "//! 싱글가방 hands that call an EMPTY name (a shipped glitch of its painter 0x1281e), so",
        "//! sprintk also remembers [`recipe_index`] of the 이름 line `\"%s %s\"` (<name>, 「조합서」)",
        "//! the same painter formats one call earlier, for exactly one call.",
        "//! Source of truth: `tools_re/add_tower_recipes.py` (`plan()`, `SHARD_NAME`).",
        "",
        "/// InGame_txt row 79 — the word the game appends to a 조합서's name on the 효과 line.",
        f"pub const MANUAL_SUFFIX: &str = {rust_str(MANUAL_SUFFIX)};",
        "",
        "/// InGame_txt row 115 — the word after the name on the 이름 line (「템플러헬름 조합서」).",
        f"pub const RECIPE_WORD: &str = {rust_str(RECIPE_WORD)};",
        "",
        "/// The game's text colour escapes (rodata 0x5b2bc) — a name starts with at most one.",
        f"pub const COLOUR_ESCAPES: &str = {rust_str(COLOUR_ESCAPES)};",
        "",
        "/// (recipe name without its colour escape, the line shown instead) — i15 rows",
        f"/// 0x{AR.FIRST:02x}..0x{AR.FIRST + len(table) - 1:02x}, in row order.",
        "#[rustfmt::skip]",
        "pub const EFFECTS: &[(&str, &str)] = &[",
    ]
    for idx, name, text in table:
        lines.append(f"    ({rust_str(name)}, {rust_str(text)}), // 0x{idx:02x}")
    lines += [
        "];",
        "",
        "/// The [`EFFECTS`] row of a 하늘성 조합서 by its name (with or without its colour escape).",
        "pub fn recipe_index(name: &str) -> Option<usize> {",
        "    let bare = name.strip_prefix(|c: char| COLOUR_ESCAPES.contains(c)).unwrap_or(name);",
        "    EFFECTS.iter().position(|(n, _)| *n == bare)",
        "}",
        "",
        "/// The line to print instead of `name + suffix`, when `suffix` is the game's",
        "/// 「의조합설명서」 and `name` is a 하늘성 조합서.",
        "pub fn manual_line(name: &str, suffix: &str) -> Option<&'static str> {",
        "    if suffix != MANUAL_SUFFIX {",
        "        return None;",
        "    }",
        "    recipe_index(name).map(|i| EFFECTS[i].1)",
        "}",
        "",
        "#[cfg(test)]",
        "mod tests {",
        "    use super::*;",
        "    use alloc::format;",
        "",
        "    #[test]",
        "    fn a_tower_recipe_shows_its_material() {",
        "        let (name, line) = EFFECTS[0];",
        "        assert_eq!(manual_line(&format!(\"\\\"{name}\"), MANUAL_SUFFIX), Some(line));",
        "        assert_eq!(manual_line(name, MANUAL_SUFFIX), Some(line));",
        "        assert_eq!(recipe_index(&format!(\"\\\"{name}\")), Some(0));",
        "    }",
        "",
        "    #[test]",
        "    fn anything_else_keeps_the_games_line() {",
        "        let (name, _) = EFFECTS[0];",
        "        assert_eq!(manual_line(name, RECIPE_WORD), None);",
        "        assert_eq!(manual_line(\"|붉은머리띠\", MANUAL_SUFFIX), None);",
        "        assert_eq!(manual_line(\"\", MANUAL_SUFFIX), None);",
        "        assert_eq!(recipe_index(\"\"), None);",
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)


def ingame_row(txt, row):
    count = struct.unpack_from("<H", txt, 2)[0]
    if count <= row:
        return None
    off = struct.unpack_from("<H", txt, 4 + 2 * row)[0]
    return txt[off:txt.index(b"\0", off)].decode("euc-kr")


def check_asset(zip_path):
    z = zipfile.ZipFile(zip_path)
    jars = [n for n in z.namelist() if n.lower().endswith(".jar")]
    jar = zipfile.ZipFile(io.BytesIO(z.read(jars[0])))
    txt = jar.read("res/dat/InGame_txt")
    bad = []
    for row, word in ((MANUAL_ROW, MANUAL_SUFFIX), (RECIPE_ROW, RECIPE_WORD)):
        got = ingame_row(txt, row)
        if got != word:
            bad.append(f"InGame_txt row {row} is {got!r}, not {word!r}")
    recs = h3crypt.records(h3crypt.decrypt_member(jar, "res/dat/i15_dat"))
    for idx, name, text in rows():
        if idx >= len(recs):
            bad.append(f"i15 row 0x{idx:02x} missing")
            continue
        body = recs[idx]
        nl = body[0]
        got = body[1:1 + nl].decode("euc-kr")
        tl = body[1 + nl + 4]
        rtext = body[2 + nl + 4:2 + nl + 4 + tl].decode("euc-kr")
        if got != '"' + name:
            bad.append(f"i15 row 0x{idx:02x} is {got!r}, the table says \"{name}")
        elif text not in rtext.split(";"):
            bad.append(f"i15 row 0x{idx:02x} ({name}) text {rtext!r} has no segment {text!r}")
    return bad


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--zip", default=DEFAULT_ZIP)
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    want = render()
    if a.check:
        if not os.path.exists(a.out):
            raise SystemExit(f"STALE: {a.out} does not exist — run this tool without --check")
        have = open(a.out, encoding="utf-8", newline="").read().replace("\r\n", "\n")
        if have != want:
            raise SystemExit(f"STALE: {a.out} differs from the recipe plan — run this tool without --check")
        bad = check_asset(a.zip)
        if bad:
            raise SystemExit("STALE asset:\n  " + "\n  ".join(bad))
        print(f"CHECK OK: {len(rows())} 하늘성 조합서 lines; InGame_txt rows {MANUAL_ROW}/{RECIPE_ROW} "
              "and the asset's recipe texts agree")
        return 0
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(want)
    print(f"wrote {a.out} ({len(rows())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
