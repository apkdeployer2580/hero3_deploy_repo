pub fn set_pad_hud_pref(p: padhud::PadHud) {
    let v = match p {
        padhud::PadHud::Auto => 0,
        padhud::PadHud::On => 1,
        padhud::PadHud::Off => 2,
    };
    PAD_HUD.store(v, std::sync::atomic::Ordering::Relaxed);
}

/// Is the pad HUD showing right now? The walk controls (arrows / stick) stand down
/// and every pad-bound control wears a position badge.
pub fn pad_hud_active() -> bool {
    pad_hud_pref().active(PAD_LAST.load(std::sync::atomic::Ordering::Relaxed))
}

/// Record which input source was used last. `true` from the gamepad entry points,
/// `false` from a screen touch — under AUTO this is what flips the HUD, so it must
/// be called from the INPUT path and never from the drawing path.
pub fn note_input_source(pad: bool) {
    PAD_LAST.store(pad, std::sync::atomic::Ordering::Relaxed);
    if pad {
        PAD_SEEN.store(true, std::sync::atomic::Ordering::Relaxed);
    }
}

/// Has this session seen any pad input? Gates the settings row only.
pub fn pad_seen() -> bool {
    PAD_SEEN.load(std::sync::atomic::Ordering::Relaxed)
}

/// For v1 the game archive is bundled as an APK asset (no file picker yet).
pub const BUNDLED_GAME_ASSET: &str = "hero3_fixed.zip";

/// `res/dat/des_dat` out of the bundled archive (`<zip>/<*.jar>/res/dat/des_dat`), or
/// `None` when either layer cannot be opened. One extra unzip at boot, once.
fn des_table_from_archive(game_zip: &[u8]) -> Option<Vec<u8>> {
    let files = wie_backend::extract_zip(game_zip).ok()?;
    let jar = files.iter().find(|(name, _)| name.ends_with(".jar")).map(|(_, bytes)| bytes)?;
    let inner = wie_backend::extract_zip(jar).ok()?;
    inner.get("res/dat/des_dat").cloned()
}

/// The archive's app id — the `PID:` line of the LGT `app_info` (KTF: `__adf__`), which is
/// the directory the record store lives under (`<data>/<pid>/db/…`, `database.rs`).
///
/// ★★★ 99차 (TODO `CG`): read HERE, before the emulator exists, so `vault::db_roots` can
/// name the live store instead of scanning `data_dir` and taking whichever `<x>/db` came
/// first — a device that once ran a KTF build has two. `None` on an archive shape this
/// does not know; the vault then falls back to the scan as before.
fn app_id_from_archive(game_zip: &[u8]) -> Option<String> {
    let files = wie_backend::extract_zip(game_zip).ok()?;
    let info = files.get("app_info").or_else(|| files.get("__adf__"))?;
    info.split(|b| *b == b'\n')
        .find_map(|line| line.strip_prefix(b"PID:"))
        .map(|pid| String::from_utf8_lossy(pid).trim().to_string())
        .filter(|pid| !pid.is_empty())
}

#[cfg(target_os = "android")]
#[unsafe(no_mangle)]
fn android_main(app: winit::platform::android::activity::AndroidApp) {
    use std::sync::{Arc, atomic::AtomicBool, mpsc::channel};

    use winit::{event_loop::EventLoop, platform::android::EventLoopBuilderExtAndroid};

    // ── ★ WHY THIS IS A PER-MODULE FILTER AND NOT JUST A LEVEL ──────────────────
    //
    // Device-measured 2026-08-04, 38 s of a live session on versionCode 5:
    //
    //     3495x  wie_core_arm::thread_wrapper: native thread; id=2
    //     1746x  wie_wipi_c::api::kernel: timer;
    //     1227x  wie_core_arm::thread_wrapper: native thread; id=3
    //
    // = **~124 `__android_log_write` calls per second, all from inside the emulator
    // tick loop.** Each one is a write to logd, on the thread whose frame budget is
    // 24 ms. This is the same class of mistake as the synchronous vibrate binder
    // call that 13차 traced (see vibration.rs): expensive I/O in the hot path.
    //
    // The old comment here assumed Info was quiet and only Debug was chatty. It is
    // not: `#[tracing::instrument]` spans default to **INFO**, and `wie` puts them on
    // `ArmCoreThreadWrapper::poll` and on the WIPI timer callback — the two things
    // that run most. We deliberately enable tracing's `log` feature (see Cargo.toml)
    // to see wie's internals, and that is what routes those spans here.
    //
    // So: everything defaults to Warn — we keep every wie warning and error,
    // including the `stub MC_knl*` notices that are how missing APIs get found — and
    // only OUR crate stays at Info. The cdylib is named `main`, so `main` is the
    // module path of every `log::` call in this app (e.g. `main::database`, which
    // NATIVE_REHOST_HANDOFF's save-verification procedure greps for).
    //
    // To get the old firehose back for a debugging session, change "warn" to "info"
    // (or "debug" for the WIPI-C DB events) in the parse string below.
    android_logger::init_once(
        android_logger::Config::default()
            .with_max_level(log::LevelFilter::Info)
            .with_filter(android_logger::FilterBuilder::new().parse("warn,main=info").build())
            .with_tag("wie"),
    );
    std::panic::set_hook(Box::new(|info| {
        log::error!("PANIC: {info}");
    }));
    log::info!("android_main: starting wie_android");

    // Read the bundled game + resolve app-private storage BEFORE the AndroidApp
    // is moved into the event loop builder.
    let game_zip = match read_asset(&app, BUNDLED_GAME_ASSET) {
        Some(bytes) => {
            log::info!("loaded asset {BUNDLED_GAME_ASSET} ({} bytes)", bytes.len());
            bytes
        }
        None => {
            log::error!("bundled game asset {BUNDLED_GAME_ASSET} not found; aborting");
            return;
        }
    };
    let data_dir = match app.internal_data_path() {
        Some(p) => p,
        None => {
            log::error!("no internal_data_path; aborting");
            return;
        }
    };
    log::info!("internal data dir = {data_dir:?}");
    let _ = DATA_DIR.set(data_dir.clone());

    // ★★★ 90차: the host judges records with the GAME's cipher from here on. The table is
    // the archive's own `res/dat/des_dat` (rebuilt from the textbook tables when the
    // archive cannot be opened — `saverecord::game_table`).
    //
    // ⛔ BEFORE the restore, not after. `apply_pending_restore` classifies every vaulted
    // generation (`vault::list`) and every candidate summary (`paired_summary`), so a
    // restore boot decides which copies are usable with whatever table is in force HERE.
    // Running it second let the stand-in table seal the `OnceLock` and this call lose in
    // silence — on the one boot the player had asked for a restore.
    vault::install_table(des_table_from_archive(&game_zip).as_deref());
    // ★★★ 99차: and the app id, for the same reason and in the same place — every boot-time
    // vault call below resolves the record store through it (TODO `CG`).
    match app_id_from_archive(&game_zip) {
        Some(id) => vault::set_app_id(&id),
        None => log::warn!("vault: the archive names no PID — the record store will be found by scanning"),
    }
    // ★ BEFORE the emulator exists, so no database is open and nothing can
    //   overwrite what we put back. A save-vault restore scheduled by the settings
    //   dialog is applied exactly here and nowhere else — see `vault.rs`.
    if let Some(what) = vault::apply_pending_restore(&data_dir) {
        log::warn!("vault: {what}");
    }
    // …and then look for the state this whole feature exists for: a character record
    // that is gone while the vault still has it.
    // ★ 130차: the save-slot WINDOW, before anything names a record. The vault's boot
    //   checks below scan every REAL slot, but the guest's first `setAppState(3)` reads
    //   `SlotSave_11_<g>` for its three rows, and the store maps those through this.
    set_slot_first(config::read_slot_first(&data_dir));
    log::warn!("save slots: window starts at real slot {} (rows show SLOT {}..{} of {})", slot_first(), slot_first() + 1, slot_first() + slotwindow::VISIBLE, slotwindow::TOTAL);
    // ★ 161차: …and the row they open on — the slot loaded last time (`wie_save_last.txt`).
    if let Some(s) = config::read_slot_last(&data_dir) {
        set_slot_focus(s);
        log::warn!("save slots: the slot lists open on SLOT {} (the last loaded slot, from wie_save_last.txt)", s + 1);
    }
    vault::check_at_boot(&data_dir);
    // …and put it back when the vault can — before the guest ever reads the slot list.
    // A slot the player 초기화'd (both records absent) is left alone; see `heal_at_boot`.
    if let Some(what) = vault::heal_at_boot(&data_dir) {
        log::warn!("vault: {what}");
    }
    // Maintenance, same place and for the same reason: before anything can be holding
    // the warehouse open. See `config::apply_wh_purge`.
    if let Some(what) = config::apply_wh_purge(&data_dir) {
        log::warn!("{what}");
    }

    // ★ Before the audio thread exists, so the very first effect already carries the
    // player's level (2026-08-27).
    set_sfx_level(config::read_sfx_level(&data_dir));
    // ★ 99차: one line, so a log from any device says which world this build lives in.
    // There is no endpoint and no mode any more — the warehouse and the cash shop are the
    // in-app engine, always (`network.rs`, `offline.rs`).
    log::warn!("net: 100% OFFLINE — the warehouse and the cash shop are served in-app; no socket is ever opened");
    // ★ 114차: and which FLAVOUR this build is — main and vanilla share the package and the
    //   versionCode sequence, so this line is the only way a logcat tells them apart.
    log::warn!("{}", flavor::boot_line());

    // Restore the saved orientation preference before the window appears.
    if config::read_landscape(&data_dir) {
        orientation::set(true);
    }

    let event_loop = EventLoop::<UserEvent>::with_user_event()
        .with_android_app(app)
        .build()
        .expect("failed to build android event loop");
    let proxy = event_loop.create_proxy();
    // Gamepad JNI relay (58차): MainActivity's dispatch hooks post through this.
    let _ = GAMEPAD_PROXY.set(std::sync::Mutex::new(event_loop.create_proxy()));

    let (input_tx, input_rx) = channel::<InputEvent>();
    let should_redraw = Arc::new(AtomicBool::new(true));
    // Shared background/lock gate. The UI thread sets it on suspend / focus-loss;
    // while set, the emulator worker stops ticking (no new sound events, saves
    // battery) and the MIDI synth emits silence — so audio does NOT keep playing
    // when the app is backgrounded or the screen is locked. Cleared on resume /
    // focus-gain (BGM resumes seamlessly).
    let paused = Arc::new(AtomicBool::new(false));
    // UI thread -> worker: how far to push the game's own top HUD band down.
    let hud_y: HudYShift = Arc::new(std::sync::atomic::AtomicU32::new(0));

    // The emulator boot is DEFERRED to the first `resumed` so the guest
    // framebuffer can be sized from the real window (landscape immersive mode).
    let pending_boot = app::PendingBoot {
        proxy,
        should_redraw,
        input_rx,
        game_zip,
        hud_y: hud_y.clone(),
    };
    let mut handler = app::App::new(input_tx, data_dir, paused, hud_y, pending_boot);
    if let Err(e) = event_loop.run_app(&mut handler) {
        log::error!("event loop exited with error: {e}");
    }
}

/// Route from the Java main thread (where `MainActivity.dispatch*` runs) to the
/// winit thread: gamepad JNI natives post `UserEvent`s through this proxy. Set once
/// in `android_main` before the event loop runs; events arriving before that (the
/// activity is not even focused yet) are dropped harmlessly.
#[cfg(target_os = "android")]
static GAMEPAD_PROXY: std::sync::OnceLock<std::sync::Mutex<winit::event_loop::EventLoopProxy<UserEvent>>> = std::sync::OnceLock::new();

#[cfg(target_os = "android")]
fn send_gamepad_event(ev: UserEvent) {
    if let Some(proxy) = GAMEPAD_PROXY.get()
        && let Ok(proxy) = proxy.lock()
    {
        // Fails only while the loop is shutting down — nothing to do about it.
        let _ = proxy.send_event(ev);
    }
}

/// The `native` methods `MainActivity` declares. Resolved by SYMBOL NAME when Java
/// calls them (`System.loadLibrary("main")` has already loaded this cdylib), so the
/// JNI naming convention in the function names is load-bearing — as is
/// `extern "system"`, the JNI calling convention.
///
/// These run on the JAVA MAIN THREAD, not the winit thread: they must only relay,
/// never touch `App` state — hence the `EventLoopProxy` hop above.
#[cfg(target_os = "android")]
/// The app-private data dir, remembered for the JNI entry points below: they are
/// called from Java with no context of their own, and the vault lives under it.
static DATA_DIR: std::sync::OnceLock<std::path::PathBuf> = std::sync::OnceLock::new();

/// Save-vault entry points for `MainActivity`'s restore dialog.
///
/// Java asks Rust rather than being handed the list, because the vault's contents
/// change while the app runs (every save rotates it) and a list captured when the
/// diagnostics dialog opened would offer generations that no longer exist.
///
/// ★ cfg-gated because `jni` is an android-only dependency: without the gate the
/// HOST build — `cargo test -p wie_android`, the documented Linux test path — does
/// not compile at all.
#[cfg(target_os = "android")]
mod vault_jni {
    use jni::{
        objects::{JObject, JString},
        sys::{jboolean, jclass, jstring},
    };

    /// `String nativeVaultList()` — `name|unix_ms|len` lines, newest first, empty
    /// when the vault holds nothing restorable.
    #[unsafe(no_mangle)]
    pub extern "system" fn Java_net_wie_emulator_MainActivity_nativeVaultList(env: *mut jni::sys::JNIEnv, _class: jclass) -> jstring {
        let lines = match crate::DATA_DIR.get() {
            Some(dir) => {
                // Opening this dialog is also the moment support gets involved, so
                // drop a copy of the whole vault somewhere a PC can reach without
                // root: `/sdcard/Android/data/<pkg>/files` is readable over plain
                // `adb pull`, and the app is not debuggable in release, so this is
                // the ONLY channel a player's backups can travel on.
                let dest = std::path::PathBuf::from("/sdcard/Android/data/com.hero3remake.app/files/save_vault");
                match crate::vault::export(dir, &dest) {
                    Ok(n) if n > 0 => log::warn!("vault: exported {n} generation(s) to {dest:?}"),
                    Ok(_) => {}
                    Err(e) => log::info!("vault: export skipped ({e})"),
                }
                crate::vault::offer_lines(dir)
            }
            None => String::new(),
        };
        let env = unsafe { jni::JNIEnv::from_raw(env) }.expect("JNIEnv");
        match env.new_string(lines) {
            Ok(s) => s.into_raw(),
            Err(e) => {
                log::error!("nativeVaultList: {e}");
                std::ptr::null_mut()
            }
        }
    }

    /// `boolean nativeVaultRestore(String key)` — schedule the restore of the
    /// generation named by one of the lines above. Applied on the NEXT launch (see
    /// `vault::apply_pending_restore`), so the caller should close the app.
    #[unsafe(no_mangle)]
    pub extern "system" fn Java_net_wie_emulator_MainActivity_nativeVaultRestore(
        env: *mut jni::sys::JNIEnv,
        _class: jclass,
        key: jstring,
    ) -> jboolean {
        let mut env = unsafe { jni::JNIEnv::from_raw(env) }.expect("JNIEnv");
        let key: JString = unsafe { JObject::from_raw(key) }.into();
        let Ok(key) = env.get_string(&key) else {
            log::error!("nativeVaultRestore: unreadable key");
            return 0;
        };
        let key: String = key.into();
        let ok = match crate::DATA_DIR.get() {
            Some(dir) => crate::vault::request_restore(dir, &key),
            None => false,
        };
        u8::from(ok)
    }
}

