/// What a field quickbar slot holds.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SlotKind {
    Empty,
    Skill,
    Item,
}

/// Which decoded-atlas icon a slot draws: an item_bm frame, or a skill sheet
/// cell `(sheet 0..6 = s4..s10, cell)`. `None` = no icon (empty / unresolved).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum IconRef {
    Item(u16),
    Skill(u8, u8),
}

/// One field-quickbar PLATE (`0..quickpage::PLATES`) for the on-screen action HUD.
/// `count` = item stack (0 for skills).
///
/// ★ `slot` is a PLATE index, not a guest slot — there are more plates than the
/// guest's five (see `quickpage.rs`). `guest` is the guest slot this plate is
/// currently resident in, i.e. the one whose `quickslot_hotkey` fires it; `None`
/// means "not in the guest's bar right now", and the worker admits it on demand.
/// The UI needs `guest` for exactly two things: placing a pad badge on the plate a
/// pad button would actually activate, and turning a pad hotkey back into the plate
/// it registers onto.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct QuickSlot {
    pub slot: u8,
    pub guest: Option<u8>,
    pub kind: SlotKind,
    pub count: u16,
    pub icon: Option<IconRef>,
}

/// Live player gauges for the HUD (from CHAR RAM — see `items.rs` for the offsets
/// and their provenance). HP is real points against a computed max; SP is the
/// game's 0..1000 scale (its max IS the constant 1000).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct Stats {
    /// TRUE current / max HP (142차): past 32767 the game only keeps a gauge, and
    /// `items::read_stats` reads the true numbers the HP hooks keep (`wie_util::stats`).
    pub hp: u32,
    pub hp_max: u32,
    pub sp: u16,
    pub sp_max: u16,
    pub exp: u32,
    pub exp_next: u32,
    pub level: u16,
    /// Unspent stat points (`CHAR+0x18a`). Drives the red `+` badge beside the
    /// gauges — the game draws exactly this badge itself, in the bottom HUD block
    /// our overlay replaces. See `items::STAT_POINTS_OFF`.
    pub stat_points: u16,
    /// Unspent skill points (`CHAR+0x18c`). Drives the blue `+` badge.
    pub skill_points: u8,
}

/// Fixed GUEST quickbar slot -> (activation key, display label). This mapping is
/// STATIC in the game image: the field action dispatcher's command jump
/// table routes number keys to a fixed selector slot — key '1'->slot0, '3'->1,
/// '9'->2, '0'->3, '#'->4 (disasm-confirmed on KTF at 0x143048, and re-confirmed on
/// LGT 2026-09-04 at the field key handler `0x4fed0`: the `cmp r4,#0x31/#0x33/#0x39/
/// #0x30/#0x23` chain at `0x4ff14` writes 0/1/2/3/4 into the selected-slot byte
/// `CHAR+0x261`, and every other key returns 0). Activating a plate therefore just
/// sends the corresponding key (fully native; no memory injection).
///
/// ⛔ The argument is a GUEST slot, never a plate. There are `quickpage::PLATES`
/// plates and only five guest slots; a plate's key is the one belonging to the guest
/// slot it is currently resident in (`QuickSlot::guest`). Feeding it a plate index
/// would fire whatever else happens to be in that guest slot — and past 4 it would
/// answer `None`, which is how the extra plates would silently stop working.
pub fn quickslot_hotkey(slot: u8) -> Option<(KeyCode, char)> {
    Some(match slot {
        0 => (KeyCode::NUM1, '1'),
        1 => (KeyCode::NUM3, '3'),
        2 => (KeyCode::NUM9, '9'),
        3 => (KeyCode::NUM0, '0'),
        4 => (KeyCode::HASH, '#'),
        _ => return None,
    })
}

