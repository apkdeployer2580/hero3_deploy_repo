pub fn note_slot_reset(slot: u8) {
    if let Ok(mut v) = SLOT_RESETS.lock() {
        v.push(slot);
        SLOT_RESET_PENDING.store(true, std::sync::atomic::Ordering::SeqCst);
    }
}

/// Every slot noted since the last call, oldest first. Empty (and lock-free) when none.
pub fn take_slot_resets() -> Vec<u8> {
    if !SLOT_RESET_PENDING.swap(false, std::sync::atomic::Ordering::SeqCst) {
        return Vec::new();
    }
    SLOT_RESETS.lock().map(|mut v| std::mem::take(&mut *v)).unwrap_or_default()
}

/// A `GameSave_11_<slot>` record-1 write (the bag payload) just reached disk durably.
/// The 재료가방 loan (`bagbox::Loan`) waits on this: once the character's bag is saved,
/// the box file may show its true debited state. `seq` advances on every commit; the low
/// byte carries the resolved slot (the write may have been redirected off the cursor).
static GAMESAVE_COMMIT: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);

/// `slot` is the slot the bytes actually landed on (post-redirect).
pub fn note_gamesave_committed(slot: u8) {
    // seq in the high bits, slot in the low 8 — one atomic, one read.
    let prev = GAMESAVE_COMMIT.load(std::sync::atomic::Ordering::Relaxed);
    let seq = (prev >> 8).wrapping_add(1);
    GAMESAVE_COMMIT.store((seq << 8) | u64::from(slot), std::sync::atomic::Ordering::SeqCst);
}

/// `(seq, slot)`. `seq` == a caller's last-seen value means no GameSave has committed since.
pub fn gamesave_commit() -> (u64, u8) {
    let v = GAMESAVE_COMMIT.load(std::sync::atomic::Ordering::SeqCst);
    (v >> 8, (v & 0xff) as u8)
}

