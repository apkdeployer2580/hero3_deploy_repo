/// Apply `pct` percent to `v`. Never returns 0 (a zero-sized control would be
/// invisible AND untappable), and the percentage is bounded so a hand-edited or
/// corrupt layout file cannot produce absurd geometry. See [`placement`], which is
/// where every player-chosen size goes through this.
pub fn scaled(v: u32, pct: u32) -> u32 {
    ((u64::from(v) * u64::from(pct.clamp(placement::PCT_MIN, placement::PCT_MAX)) / 100) as u32).max(1)
}

/// Resolve the guest framebuffer size ONCE, from the window the game will run
/// in. `None` (or a portrait window) keeps the original 240x320.
///
/// Called before the emulator thread starts; the WIPI screen framebuffer is
/// allocated once at `MC_grpGetScreenFrameBuffer` and its pointer is cached by
/// the guest, so this cannot change while the game runs.
/// `landscape_pref` = the persisted orientation choice, NOT `win_w > win_h`.
/// Device-confirmed race (2026-07-28): `orientation::set(true)` is issued before
/// the event loop, so the FIRST `resumed` can still report the pre-rotation
/// PORTRAIT size (seen: launch A 2340x1080, launch B 1080x2340 on the same
/// device with the same config). Sizing off that transient value silently
/// dropped immersive mode every other launch — so derive the aspect from the
/// window's long/short sides plus the preference the activity will settle into.
pub fn init_logical(win_w: u32, win_h: u32, landscape_immersive: bool, landscape_pref: bool, base_h: u32) -> (u32, u32) {
    let (long, short) = (win_w.max(win_h), win_w.min(win_h));
    let size = if landscape_immersive && landscape_pref && short > 0 {
        let base = base_h.max(120);
        // even width keeps the 2-byte-per-pixel guest stride tidy
        let w = ((u64::from(base) * u64::from(long) / u64::from(short)) as u32).clamp(LOGICAL_W_MIN, LOGICAL_W_MAX.min(POPUP_SAFE_LOGICAL_W)) & !1;
        // Derive the height BACK from the (possibly clamped) width so the frame
        // still fills the window 1:1 — a clamp applied to the width alone would
        // stretch the picture. On aspects up to 2.07:1 nothing is clamped and this
        // returns `base` unchanged (±1 px of integer rounding).
        let h = ((u64::from(w) * u64::from(short) / u64::from(long)) as u32).max(120);
        (w, h)
    } else {
        (CONTENT_W, CONTENT_H)
    };
    let _ = LOGICAL.set(size);
    let _ = IMMERSIVE.set(size != (CONTENT_W, CONTENT_H));
    logical()
}

/// The guest framebuffer size in use (240x320 until [`init_logical`] runs).
pub fn logical() -> (u32, u32) {
    *LOGICAL.get().unwrap_or(&(CONTENT_W, CONTENT_H))
}

/// True when the guest runs at an aspect-matched wide framebuffer, i.e. the
/// window is filled 1:1 by the game and the controls are translucent overlays.
pub fn immersive_active() -> bool {
    *IMMERSIVE.get().unwrap_or(&false)
}

/// 조작 방식 — what the ONE walk seat (`placement::CtrlId::Stick`) is on the FIELD.
/// Three answers since 2026-09-22 (player: *"자유스틱, 십자키, 고정스틱 3가지로 바꿀꺼야
/// … 고정스틱은 자유스틱이랑 똑같이 조이스틱인데 십자키처럼 위치가 고정된
/// 조이스틱"*):
///
///  * [`Float`](StickMode::Float) — 자유 스틱, the shipped default: the whole window is
///    the stick zone and the base spawns wherever the finger lands.
///  * [`Dpad`](StickMode::Dpad) — 십자키 (2026-08-16, revised the same day): the field
///    walks with the four-arrow D-pad and the stick is hidden outright — the first
///    B was a stick pinned to its seat, and the player asked for arrows only
///    ("화살표만 나와야해 … 조이스틱은 터치타입 B에서 히든처리").
///  * [`Pinned`](StickMode::Pinned) — 고정 스틱: the same stick as `Float`, with the
///    base nailed to the seat the way the arrows are. That first "B" again, now as
///    its own choice instead of as a replacement for the arrows.
///
/// ★ Since 91차 all three draw from the SAME seat — the mode decides what that
/// square shows on the field (a disc at its centre, or the four arrows) and where a
/// drag's centre comes from, not which of several controls exists.
///
/// ⛔ `Dpad` is the ONLY mode with no stick. Ask [`StickMode::field_arrows`] /
/// [`StickMode::stick_on_field`] rather than comparing variants at a call site: the
/// old `stick_fixed()` bool answered both questions with one bit and adding a third
/// mode is exactly where that breaks.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum StickMode {
    /// 자유 스틱 — touch anywhere on the field; the base spawns under the finger.
    Float,
    /// 십자키 — four pinned arrows; no stick at all.
    Dpad,
    /// 고정 스틱 — a stick whose base never leaves its seat.
    Pinned,
}

impl StickMode {
    pub(crate) const FLOAT: u8 = 0;
    pub(crate) const DPAD: u8 = 1;
    pub(crate) const PINNED: u8 = 2;

    fn from_u8(v: u8) -> Self {
        match v {
            Self::DPAD => Self::Dpad,
            Self::PINNED => Self::Pinned,
            _ => Self::Float,
        }
    }

    fn to_u8(self) -> u8 {
        match self {
            Self::Float => Self::FLOAT,
            Self::Dpad => Self::DPAD,
            Self::Pinned => Self::PINNED,
        }
    }

    /// Does the FIELD walk with the four arrows? `Dpad` only — both stick modes draw
    /// a base there instead. (Off the field every mode draws the arrows: they are the
    /// menu cursor keys, which is a different question entirely.)
    pub fn field_arrows(self) -> bool {
        self == Self::Dpad
    }

    /// Is there a stick on the field at all? Everything that publishes, draws or
    /// hit-tests a stick asks this — `Dpad` is the one mode that must answer no.
    pub fn stick_on_field(self) -> bool {
        self != Self::Dpad
    }

    /// Does a drag's centre come from the SEAT rather than from the finger's landing
    /// point? `Pinned` only. See `App::joy_start`.
    pub fn stick_is_pinned(self) -> bool {
        self == Self::Pinned
    }

    /// The next mode in the settings row's cycle, in the order the player named them:
    /// 자유 스틱 → 십자키 → 고정 스틱 → 자유 스틱.
    pub fn next(self) -> Self {
        match self {
            Self::Float => Self::Dpad,
            Self::Dpad => Self::Pinned,
            Self::Pinned => Self::Float,
        }
    }

    /// The settings row's sub-label.
    pub fn label(self) -> &'static str {
        match self {
            Self::Float => "자유 스틱",
            Self::Dpad => "십자키",
            Self::Pinned => "고정 스틱",
        }
    }
}

pub fn stick_mode() -> StickMode {
    StickMode::from_u8(STICK_MODE.load(std::sync::atomic::Ordering::Relaxed))
}

pub fn set_stick_mode(m: StickMode) {
    STICK_MODE.store(m.to_u8(), std::sync::atomic::Ordering::Relaxed);
}

