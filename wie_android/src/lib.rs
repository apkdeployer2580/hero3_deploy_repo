/// The guest's quit request, in three states: 0 = nobody asked, 1 = asked and the
/// worker has not dealt with it yet, 2 = the worker is done and the UI may tear down.
///
/// ── WHY THIS EXISTS (2026-08-20, 60차) ──────────────────────────────────────
/// Player report: "종료 버튼을 눌러도 종료가 되지 않아 강제로 홈으로 나간 다음 직접
/// 밀어서 종료해야하고". They were right, and it was one line:
/// `platform::exit` logged "guest requested exit" and returned. `MC_knlExit` IS
/// wired for both carriers (`wie_lgt/src/runtime/wipi_c.rs`, `WIPICSvcId::Exit`),
/// so the game's 종료 menu reached the host every time and the host did nothing.
///
/// It is not a cosmetic bug. A player who cannot quit force-swipes the task away
/// instead, which kills the process at an arbitrary instant — and until this
/// session's `write_atomic` that could catch a record mid-write. So the fix is
/// "quit properly AND save on the way out", not just "quit".
static EXIT_REQUEST: std::sync::atomic::AtomicU8 = std::sync::atomic::AtomicU8::new(0);

/// `MC_knlExit` landed. Called from `platform::exit` on whatever thread the guest
/// happened to be on; idempotent, because a game that asks twice must not restart
/// the shutdown.
pub fn request_exit() {
    let prev = EXIT_REQUEST.swap(1, std::sync::atomic::Ordering::SeqCst);
    if prev == 0 {
        log::warn!("exit: guest requested quit");
    }
}

/// `true` once, for the worker: "deal with the quit now". Later calls return false,
/// so the worker's shutdown block runs exactly once.
pub fn take_exit_request() -> bool {
    EXIT_REQUEST
        .compare_exchange(1, 2, std::sync::atomic::Ordering::SeqCst, std::sync::atomic::Ordering::SeqCst)
        .is_ok()
}

/// Has a quit been requested at all? Used by the worker to stop pretending the
/// guest still needs ticking.
pub fn exiting() -> bool {
    EXIT_REQUEST.load(std::sync::atomic::Ordering::SeqCst) != 0
}

/// Save slots whose character was just 초기화'd (`AndroidDatabaseRepository::delete` on
/// `GameSave_11_<n>`), waiting for the worker to drop that slot's plate row
/// (`quickpage::Pages::forget_slot`). The repository runs inside the guest's tick and
/// cannot reach the worker's store, so it leaves a note; the flag spares the worker a
/// lock per frame when — as almost always — there is nothing to take.
static SLOT_RESETS: std::sync::Mutex<Vec<u8>> = std::sync::Mutex::new(Vec::new());
static SLOT_RESET_PENDING: std::sync::atomic::AtomicBool = std::sync::atomic::AtomicBool::new(false);

/// Is the game drawing a bag CELL cursor right now (`menutouch::cell_box`)?
