/// The count LATCHED at the moment the player confirmed a purchase.
///
/// ★ 2026-08-21, device-reported: "오브원석은 잘 들어가는데 소켓확장은 수량을 여러개 사도
/// 1개만 들어와". The two travel by different roads and only one of them was safe.
/// 오브원석 is granted by the CLIENT out of its own row, and the host writes that row on
/// the commit key — the value is captured before anything else can run. 오브상자 and
/// 소켓확장 are delivered by the ENGINE, which reads the count when the `05 42` frame
/// arrives, strictly later — and by then the picker may have been dismissed, which used
/// to reset the live value to 1. So the count the player actually confirmed is latched
/// here, and the engine reads the latch rather than the live spinner.
static CASH_QTY_COMMITTED: std::sync::atomic::AtomicU8 = std::sync::atomic::AtomicU8::new(0);

/// Latch the count for a purchase the player has just confirmed. Called from the commit
/// key path, so it lands before the guest can send anything.
pub fn commit_cash_qty(n: u8) {
    CASH_QTY_COMMITTED.store(n.clamp(1, CASH_QTY_MAX), std::sync::atomic::Ordering::Relaxed);
}

/// The count a purchase in flight should use: the latched one if a confirm has happened,
/// otherwise the live spinner.
///
/// The latch is never cleared, only overwritten — every confirm writes it, including a
/// plain 1. Clearing it would need to happen after the engine has read it, and the whole
/// point of the latch is that we cannot know when that is.
pub fn cash_qty_committed() -> u8 {
    match CASH_QTY_COMMITTED.load(std::sync::atomic::Ordering::Relaxed) {
        0 => cash_qty(),
        n => n.clamp(1, CASH_QTY_MAX),
    }
}

